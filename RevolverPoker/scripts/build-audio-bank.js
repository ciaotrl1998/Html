import { readFile, writeFile } from 'node:fs/promises';
import { SOUND_FILES } from '../client/audio.js';

// Keep editable production WAV files, but deliver sound bytes as JavaScript so
// browser download managers do not capture individual audio requests.
const data = {};
for (const [name, path] of Object.entries(SOUND_FILES)) {
  const bytes = await readFile(new URL('..' + path, import.meta.url));
  if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WAVE') {
    throw new Error(`Invalid WAV: ${path}`);
  }
  data[name] = bytes.toString('base64');
}
const source = '// Generated by scripts/build-audio-bank.js from client/assets/audio/*.wav.\n'
  + '// Runtime data only; no separate audio downloads.\n'
  + `export const SOUND_DATA = Object.freeze(${JSON.stringify(data, null, 2)});\n`;
await writeFile(new URL('../client/audio-bank.js', import.meta.url), source);
console.log(`Audio bank: ${Object.keys(data).length} sounds`);
