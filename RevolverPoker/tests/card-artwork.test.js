import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { CARD_ART_SIZE, cardArtImage, cardArtURL, cardDisplayImage, loadCardArtwork } from '../client/card-artwork.js';
import { paintSettlementCard } from '../client/settlement-label.js';

test('every fixed face/back PNG is packaged at the declared size with a unique, verified image', async () => {
  const root = new URL('../client/assets/cards/', import.meta.url);
  const manifest = JSON.parse(await readFile(new URL('manifest.json', root), 'utf8'));
  assert.equal(Object.keys(manifest.files).length, 54);
  const hashes = new Set();
  for (const [name, hash] of Object.entries(manifest.files)) {
    const data = await readFile(new URL(name, root));
    assert.equal(data.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
    assert.equal(createHash('sha256').update(data).digest('hex'), hash, name);
    assert.deepEqual([data.readUInt32BE(16), data.readUInt32BE(20)], name === 'display.png' ? [1716, 865] : [CARD_ART_SIZE.width, CARD_ART_SIZE.height]);
    assert.ok(!hashes.has(hash), `${name} must not duplicate another face`); hashes.add(hash);
  }
  for (let i = 0; i < 52; i++) assert.ok(manifest.files[`${String(i).padStart(2, '0')}.png`]);
  assert.ok(cardArtURL(null).endsWith('/back.png')); assert.ok(cardArtURL(51).endsWith('/51.png'));
  const source = await readFile(new URL('../client/cards.js', import.meta.url), 'utf8');
  assert.doesNotMatch(source, /CanvasTexture|fillText|drawFront|drawBack/, '3D card artwork is never generated by browser fonts');
});

test('preloading decodes all artwork once and both known/unknown result cards use fixed atlas pixels', async t => {
  const previous = Object.getOwnPropertyDescriptor(globalThis, 'document');
  let created = 0, decoded = 0;
  class Image {
    constructor() { created++; this.complete = false; this.naturalWidth = 0; }
    set src(value) { this.url = value; queueMicrotask(() => { this.complete = true; this.naturalWidth = this.width; this.onload?.(); }); }
    decode() { decoded++; return Promise.resolve(); }
  }
  Object.defineProperty(globalThis, 'document', { configurable: true, value: { createElement: tag => { assert.equal(tag, 'img'); return new Image(); } } });
  t.after(() => { if (previous) Object.defineProperty(globalThis, 'document', previous); else delete globalThis.document; });
  const first = loadCardArtwork(); assert.equal(first, loadCardArtwork()); await first;
  assert.equal(created, 54); assert.equal(decoded, 54);
  assert.equal(cardArtImage(0), cardArtImage(0)); assert.equal(created, 54);
  const calls = [];
  const ctx = new Proxy({}, { get: (obj, key) => key in obj ? obj[key] : (...args) => calls.push({ key, args }) });
  paintSettlementCard(ctx, 25, 10, 20, true, { glow: true });
  paintSettlementCard(ctx, null, 160, 20);
  const draws = calls.filter(call => call.key === 'drawImage');
  assert.equal(draws.length, 2); assert.equal(draws[0].args[0], cardDisplayImage());
  assert.deepEqual(draws[0].args.slice(1), [12 * 132, 173, 132, 173, 10, 20, 132, 173]);
  assert.deepEqual(draws[1].args.slice(1), [0, 4 * 173, 132, 173, 160, 20, 132, 173]);
  assert.ok(!calls.some(call => call.key === 'fillText'), 'no runtime rank/suit glyph rendering remains');
});

test('a missing fixed texture fails loading explicitly instead of silently drawing a white card', async t => {
  const { loadCardArtwork: loadMissing } = await import('../client/card-artwork.js?missing-test');
  const previous = Object.getOwnPropertyDescriptor(globalThis, 'document');
  class Image {
    set src(value) { queueMicrotask(() => value.endsWith('/00.png') ? this.onerror?.() : this.onload?.()); }
  }
  Object.defineProperty(globalThis, 'document', { configurable: true, value: { createElement: () => new Image() } });
  t.after(() => { if (previous) Object.defineProperty(globalThis, 'document', previous); else delete globalThis.document; });
  await assert.rejects(loadMissing(), /固定牌面贴图加载失败：00\.png/);
});
